export interface TemplateContext {
  appName: string;
  slug: string;
  coreVersion: string;
  distributionMode: "dependency" | "owned";
}

const webPackageName = (context: TemplateContext): string => context.slug + "-web";
const workerPackageName = (context: TemplateContext): string => context.slug + "-worker";
const coreDependency = (context: TemplateContext): string =>
  context.distributionMode === "owned" ? "workspace:*" : context.coreVersion;
const lines = (values: string[]): string => values.join("\n") + "\n";

