export const readme = (context: TemplateContext): string =>
  `# ${context.appName}

A thin composition root generated by \`@emi/create-chat-app\`. Application logic — conversations,
messages, branches, resumable generation, memory, notes, and the chat shell UI — lives entirely in
released/workspace core packages:

- \`@emi/core/contract\` — schemas and API contracts
- \`@emi/core/server\` — auth, conversations, branches, generation, memory, notes
- \`@emi/core/web\` — chat shell, composer, sidebar, settings
- \`@emi/core/cloudflare\` — D1, R2, Durable Object, Worker, and Alchemy adapters

Nothing under \`web/\` or \`worker/\` in this generated tree is a copy of core package source. Both
sub-packages only import the packages above by name (currently pinned to \`${context.coreVersion}\`).
Upgrading is a normal dependency bump in \`web/package.json\` and \`worker/package.json\`, not a manual
port.

## Layout

\`\`\`text
web/       Vite + React composition root depending on @emi/core/web + @emi/core/contract
worker/    Alchemy Cloudflare Worker composition root depending on @emi/core/server + @emi/core/cloudflare
\`\`\`

## Getting started

Add \`web\` and \`worker\` to a pnpm workspace that also resolves the \`@emi/core\` packages (this
repository's root workspace already does, if this directory was generated under \`apps/\`). Then:

\`\`\`bash
pnpm install
pnpm --filter ${webPackageName(context)} typecheck
pnpm --filter ${workerPackageName(context)} typecheck
pnpm --filter ${workerPackageName(context)} db:generate
pnpm --filter ${webPackageName(context)} dev
pnpm --filter ${workerPackageName(context)} dev
\`\`\`

A product flavor adds nav, pages, tools, and prompt fragments by passing \`CoreWebContributions\` to
\`CoreWebProvider\` (web) and by merging an \`AppDefinition\` with \`coreAppDefinition\` (worker) — see
\`apps/generic-web\` and \`apps/generic-worker\` in the upstream monorepo for a worked example.

## Deferred

Real npm publishing of the \`@emi/core\` package is deferred; until then, the generated
dependency version (\`${context.coreVersion}\`) only resolves inside a pnpm workspace that also
contains that package as a member.
`;

